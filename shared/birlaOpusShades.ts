export function searchBirlaOpusShades(
  query: string,
  familyFilter?: string
): BirlaOpusShade[] {
  const normalizedQuery = query.trim().toLowerCase().replace(/\s+/g, " ");
  const strippedQuery = normalizedQuery.replace(/[^a-z0-9]/g, "");

  return birlaOpusShades.filter((shade) => {
    // Colour family filter check
    if (familyFilter && familyFilter !== "All") {
      const matchExact = shade.family === familyFilter;
      const matchPartial =
        familyFilter === "Greens" && (shade.family === "Greens" || shade.family === "Yellow-Greens" || shade.family === "Blue-Greens");
      const matchBlues =
        familyFilter === "Blues" && (shade.family === "Blues" || shade.family === "Blue-Greens");
      if (!matchExact && !matchPartial && !matchBlues) {
        return false;
      }
    }

    if (!normalizedQuery) {
      return true;
    }

    const codeNorm = shade.code.toLowerCase();
    const codeStripped = shade.code.toLowerCase().replace(/[^a-z0-9]/g, "");
    const nameNorm = shade.name.toLowerCase();

    // 1. Exact or partial code matching (e.g. "NN 9084", "9084", "NN9084")
    if (codeNorm.includes(normalizedQuery) || codeStripped.includes(strippedQuery)) {
      return true;
    }

    // 2. Name matching (e.g. "A Camel Called Rani", "camel called rani")
    if (nameNorm.includes(normalizedQuery)) {
      return true;
    }

    // 3. Word token matching
    const queryTokens = normalizedQuery.split(" ").filter((t) => t.length > 1);
    if (queryTokens.length > 0 && queryTokens.every((token) => nameNorm.includes(token) || codeNorm.includes(token))) {
      return true;
    }

    return false;
  });
}

